export type Nutrition = {
  calories: number;
  protein: number;
  fat: number;
  carbs: number;
};

type Entry = Nutrition & { key: string };

/** Türkçe metni sadeleştirir: küçük harf + aksan/işaret temizliği. */
function norm(s: string): string {
  return s
    .toLocaleLowerCase("tr")
    .replaceAll("ç", "c")
    .replaceAll("ş", "s")
    .replaceAll("ğ", "g")
    .replaceAll("ı", "i")
    .replaceAll("i̇", "i")
    .replaceAll("ö", "o")
    .replaceAll("ü", "u")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

